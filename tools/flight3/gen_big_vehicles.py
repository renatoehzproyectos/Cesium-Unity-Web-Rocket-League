def tbl(rows, var="aero/alpha-rad"):
    return "<table><independentVar lookup=\"row\">%s</independentVar><tableData>\n%s\n</tableData></table>" % (var, "\n".join("%g %g" % r for r in rows))

def contact(name, x, y, z, k, c, steer=0, brake="NONE", f_static=0.8, f_dyn=0.5, f_roll=0.02, retract=1):
    return f"""    <contact type="BOGEY" name="{name}">
      <location unit="IN"><x> {x*M2IN:.1f} </x><y> {y*M2IN:.1f} </y><z> {z*M2IN:.1f} </z></location>
      <static_friction> {f_static} </static_friction><dynamic_friction> {f_dyn} </dynamic_friction><rolling_friction> {f_roll} </rolling_friction>
      <spring_coeff unit="LBS/FT"> {k:.0f} </spring_coeff><damping_coeff unit="LBS/FT/SEC"> {c:.0f} </damping_coeff>
      <max_steer unit="DEG"> {steer} </max_steer><brake_group> {brake} </brake_group><retractable>{retract}</retractable>
    </contact>"""

def kin(name, inp, out, t_full, lo=0, hi=1):
    return f"""      <kinematic name="{name}"><input>{inp}</input><traverse>
        <setting><position>{lo}</position><time>0</time></setting><setting><position>{hi}</position><time>{t_full}</time></setting></traverse><output>{out}</output></kinematic>"""

def turbofan(src_file, name, thrust_lbf, tsfc, out_dir):
    """JSBSim's own JT9D-3 turbofan tables with the thrust (and fuel flow) replaced."""
    t = open(os.path.join(JSB, "engine", src_file)).read()
    t = re.sub(r"<milthrust>[^<]*</milthrust>", "<milthrust> %.1f </milthrust>" % thrust_lbf, t)
    t = re.sub(r"<tsfc>[^<]*</tsfc>", "<tsfc> %g </tsfc>" % tsfc, t)
    t = re.sub(r'<turbine_engine name="[^"]*">', '<turbine_engine name="%s">' % name, t)
    open(os.path.join(out_dir, name + ".xml"), "w").write(t)

