#!/usr/bin/env python3
"""Generate Assets/Scripts/Sim/Fpv/FpvPresets.cs from ShramkoGSFPV's packages/sim-core/presets/*.json.

    python3 gen_presets.py /path/to/ShramkoGSFPV-main
"""
import glob, json, os, sys

root = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SHRAMKO_DIR", "")
if not root:
    sys.exit("usage: gen_presets.py /path/to/ShramkoGSFPV-main")
out = os.path.join(os.path.dirname(__file__), "..", "..", "Assets", "Scripts", "Sim", "Fpv", "FpvPresets.cs")

RATES = {"BETAFLIGHT": "Betaflight", "RACEFLIGHT": "Raceflight", "KISS": "Kiss", "ACTUAL": "Actual", "QUICK": "Quick"}

def n(v):
    s = repr(float(v))
    if s.endswith(".0"): s = s[:-2]
    return s

def arr(a): return "new double[] { " + ", ".join(n(x) for x in a) + " }"
def axis(a): return f"new AxisRates({n(a[0])}, {n(a[1])}, {n(a[2])})"

items = []
for f in sorted(glob.glob(os.path.join(root, "packages", "sim-core", "presets", "*.json"))):
    d = json.load(open(f))
    F = {k: v["value"] for k, v in d["fields"].items()}
    r = F["rates"]
    lvl = F.get("level", {})
    lines = [
        f'            new FpvPreset {{',
        f'                id = "{d["id"]}", name = "{d["name"]}", cls = "{d["class"]}",',
        f'                wheelbaseMm = {n(F["wheelbase_mm"])}, motorKv = {n(F["motor_kv"])}, propDiameterMm = {n(F.get("prop_diameter_mm", 0))}, auwG = {n(F["auw_g"])}, twr = {n(F["twr"])},',
        f'                batteryCells = {n(F["battery_cells"])}, batteryCapacityMah = {n(F["battery_capacity_mah"])},',
        f'                inertiaRollPitch = {n(F["inertia_roll_pitch_kgm2"])}, inertiaYaw = {n(F["inertia_yaw_kgm2"])}, motorTauMs = {n(F["motor_tau_ms"])}, motorKappaM = {n(F["motor_kappa_m"])},',
        f'                motorIdle = {n(F["motor_idle"])}, rpmLoadedFraction = {n(F["rpm_loaded_fraction"])},',
        f'                cdaHorizontalCm2 = {n(F["cda_horizontal_cm2"])}, cdaVerticalCm2 = {n(F["cda_vertical_cm2"])},',
        f'                colliderDuctRadiusMm = {n(F["collider_duct_radius_mm"])}, colliderDuctOffsetMm = {n(F["collider_duct_offset_mm"])}, colliderBodyRadiusMm = {n(F["collider_body_radius_mm"])},',
        f'                vBounceMs = {n(F["v_bounce_ms"])}, vCrashMs = {n(F["v_crash_ms"])}, packResistancePerCellOhm = {n(F["pack_resistance_per_cell_ohm"])}, efficiency = {n(F["efficiency"])},',
        f'                cameraUptiltDeg = {n(F["camera_uptilt_deg"])}, cameraFovDeg = {n(F["camera_fov_deg"])},',
        f'                rates = new RatesConfig {{ type = RatesType.{RATES[r["type"]]}, roll = {axis(r["roll"])}, pitch = {axis(r["pitch"])}, yaw = {axis(r["yaw"])}, rateLimit = {n(r["rate_limit"])} }},',
        f'                pidRoll = {arr(F["pid_roll"])}, pidPitch = {arr(F["pid_pitch"])}, pidYaw = {arr(F["pid_yaw"])},',
        f'                throttle = new ThrottleCurve({n(F["throttle"]["mid"])}, {n(F["throttle"]["expo"])}),',
        f'                rotorDragPerS = {n(F["rotor_drag_per_s"])}, rotorInertiaKgm2 = {n(F["rotor_inertia_kgm2"])},',
        f'                wakeLoss = {n(F.get("wake_loss", 0))}, wakeShake = {n(F.get("wake_shake", 0))},',
    ]
    if "angle_feedforward" in lvl: lines.append(f'                levelFfGain = {n(lvl["angle_feedforward"] / 100)},')
    if "angle_feedforward_smoothing_ms" in lvl: lines.append(f'                levelFfSmoothMs = {n(lvl["angle_feedforward_smoothing_ms"])},')
    lines.append("            }")
    items.append("\n".join(lines))

src = f'''// GENERATED by tools/fpv/gen_presets.py from ShramkoGSFPV packages/sim-core/presets/*.json (MIT, Andrii Shramko). Do not edit by hand.
// Every number there carries its source (manufacturer / measured / estimate / bf-default); read the JSON for the provenance.
namespace RocketWorld.Sim.Fpv
{{
    public static class FpvPresets
    {{
        /// <summary>The drone ShramkoGSFPV starts with.</summary>
        public const string DefaultId = "pavo20pro-3s";

        public static readonly FpvPreset[] All = new[]
        {{
{(","+chr(10)).join(items)}
        }};

        public static FpvPreset Get(string id)
        {{
            foreach (var p in All) if (p.id == id) return p;
            return All[0];
        }}

        public static int IndexOf(string id)
        {{
            for (int i = 0; i < All.Length; i++) if (All[i].id == id) return i;
            return 0;
        }}
    }}
}}
'''
open(out, "w").write(src)
print("wrote", os.path.relpath(out), len(items), "presets")
